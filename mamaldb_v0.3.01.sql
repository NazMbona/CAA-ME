-- ============================================================
-- Mayan EDMS companion legal case database
-- Cleaner PostgreSQL schema for a law firm / case management system
-- ============================================================

CREATE SCHEMA IF NOT EXISTS lawfirm;

SET search_path TO lawfirm, public;

-- ---------- Common information: geography ----------

CREATE TABLE IF NOT EXISTS lawfirm.ci_countries (
    country_id VARCHAR(2) NOT NULL,
    name_country VARCHAR(100),
    country_nationality VARCHAR(100),
    PRIMARY KEY (country_id)
);

CREATE TABLE IF NOT EXISTS lawfirm.ci_states (
    state_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id VARCHAR(2) NOT NULL,
    state_name VARCHAR(100) NOT NULL,
    CONSTRAINT ci_states_country_name_unique UNIQUE (country_id, state_name)
);

CREATE TABLE IF NOT EXISTS lawfirm.ci_localities (
    locality_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locality_state_id INTEGER NOT NULL,
    locality_name VARCHAR(100) NOT NULL,
    CONSTRAINT ci_localities_state_name_unique UNIQUE (locality_state_id, locality_name)
);

-- ---------- Common information: forums (courts, tribunals, arbitration) ----------

CREATE TABLE IF NOT EXISTS lawfirm.ci_forums (
    forum_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forum_name VARCHAR(255) NOT NULL,
    forum_type VARCHAR(50) NOT NULL
        CHECK (forum_type IN (
            'Superior Court',
            'Subordinate Court',
            'Tribunal',
            'Arbitral Tribunal',
            'Arbitration Centre',
            'Other'
        )),
    forum_station VARCHAR(100),
    forum_address VARCHAR(100),
    forum_locality_id INTEGER NULL,
    forum_zip VARCHAR(10),
    CONSTRAINT ci_forums_name_station_locality_unique
        UNIQUE (forum_name, forum_station, forum_locality_id)
);

-- ---------- Common information: legal entities and advocates ----------

CREATE TABLE IF NOT EXISTS lawfirm.ci_legalentities (
    legalentity_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(50) NOT NULL
        CHECK (entity_type IN (
            'Private Law Firm',
            'Sole Practitioner',
            'State Prosecutor (ODPP)',
            'Attorney-General',
            'Other Government Legal Office',
            'Other'
        )),
    entity_name VARCHAR(255) NOT NULL,
    entity_address VARCHAR(100),
    entity_locality INTEGER NULL
);

CREATE TABLE IF NOT EXISTS lawfirm.ci_advocates (
    advocate_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advocate_name_first VARCHAR(50),
    advocate_name_sur VARCHAR(50) NOT NULL,
    advocate_name_others VARCHAR(100),
    advocate_legalentity INTEGER NULL,
    CONSTRAINT ci_advocates_name_unique
        UNIQUE (advocate_name_first, advocate_name_sur, advocate_name_others)
);

-- ---------- Client / customer records ----------

CREATE TABLE IF NOT EXISTS lawfirm.ar_customers (
    customer_id VARCHAR(8) NOT NULL,
    customer_type VARCHAR(20) NOT NULL
        CHECK (customer_type IN ('Individual', 'Company')),
    name_first VARCHAR(50),
    name_sur VARCHAR(50),
    name_others VARCHAR(100),
    date_birth DATE,
    nationality_country_id VARCHAR(2),
    residence_country_id VARCHAR(2),
    phone_primary VARCHAR(16),
    phone_secondary VARCHAR(16),
    email VARCHAR(255),
    name_company VARCHAR(100),
    physical_address VARCHAR(100),
    physical_locality INTEGER,
    physical_zip VARCHAR(10),
    postal_address VARCHAR(100),
    postal_locality INTEGER,
    postal_zip VARCHAR(10),
    id_type VARCHAR(25)
        CHECK (id_type IN ('National ID', 'Passport', 'Alien ID')),
    id_number VARCHAR(30),
    id_issue_date DATE,
    id_expiry_date DATE,
    id_scanfront VARCHAR(255),
    id_scanback VARCHAR(255),
    PRIMARY KEY (customer_id),

    CONSTRAINT ar_customers_person_or_company CHECK (
        (
            customer_type = 'Individual'
            AND name_first IS NOT NULL
            AND name_sur IS NOT NULL
        )
        OR
        (
            customer_type = 'Company'
            AND name_company IS NOT NULL
        )
    ),

    CONSTRAINT ar_customers_email_format CHECK (
        email IS NULL
        OR email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
    ),

    CONSTRAINT ar_customers_id_dates CHECK (
        id_issue_date IS NULL
        OR id_expiry_date IS NULL
        OR id_expiry_date >= id_issue_date
    )
);

-- ---------- Case categories (self-referencing hierarchy) ----------

CREATE TABLE IF NOT EXISTS lawfirm.ci_case_categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL,
    parent_id INTEGER NULL,
    CONSTRAINT ci_case_categories_name_parent_unique UNIQUE (parent_id, category_name),
    CONSTRAINT ci_case_categories_no_self_parent CHECK (
        parent_id IS NULL OR parent_id <> category_id
    )
);

-- ---------- Cases ----------

CREATE TABLE IF NOT EXISTS lawfirm.ci_cases (
    case_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_internal_reference_id VARCHAR(12) NOT NULL UNIQUE,
    date_created TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    customer_id VARCHAR(8) NOT NULL,
    forum_id INTEGER NOT NULL,
    forum_case_number VARCHAR(50) NOT NULL,
    date_forum_filing DATE,
    case_type INTEGER NOT NULL,
    case_assigned_advocate INTEGER NULL,
    claim_nature TEXT,
    case_status VARCHAR(20) NOT NULL CHECK (case_status IN (
        'Active',
        'Pending',
        'Stayed',
        'Concluded',
        'Archived'
    )),
    CONSTRAINT ci_cases_forum_case_number_unique UNIQUE (forum_id, forum_case_number)
);

-- Opposing advocates: many-to-many join table
CREATE TABLE IF NOT EXISTS lawfirm.ci_case_opposing_advocates (
    case_id INTEGER NOT NULL,
    advocate_id INTEGER NOT NULL,
    role VARCHAR(50),
    PRIMARY KEY (case_id, advocate_id)
);

-- ---------- Case events ----------

CREATE TABLE IF NOT EXISTS lawfirm.ci_case_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id INTEGER NOT NULL,
    event_type VARCHAR(30) NOT NULL
        CHECK (event_type IN (
            'Hearing',
            'Mention',
            'Ruling',
            'Submission Deadline'
        )),
    event_date DATE NOT NULL,
    event_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------- Case Links ----------

CREATE TABLE IF NOT EXISTS lawfirm.mayan_case_links (
    link_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_internal_reference_id VARCHAR(12) NOT NULL,
    mayan_document_id BIGINT NOT NULL,
    mayan_metadata_key VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (case_internal_reference_id, mayan_document_id, mayan_metadata_key)
);

-- ---------- Foreign keys ----------

ALTER TABLE lawfirm.ci_states
ADD CONSTRAINT ci_states_country_fk
FOREIGN KEY (country_id) REFERENCES lawfirm.ci_countries(country_id)
ON UPDATE NO ACTION ON DELETE NO ACTION;

